"""Measure how much Haven catches on fictional clinical notes.

    python -m benchmark.run            # prints a summary, writes benchmark/RESULTS.md
    python -m benchmark.run --show 20  # also prints 20 example leaks

A planted identifier counts as caught only if none of its parts survive. For a
name, that means neither the first nor the last name is left anywhere in the
note. A note is clean only if every identifier in it was caught.
"""

from __future__ import annotations

import argparse
import re
import time
from collections import defaultdict
from pathlib import Path

from presidio_analyzer import AnalyzerEngine

from app.core.offline import force_offline
from app.core.sanitizer import Sanitiser, ScrubResult, TokenMap
from benchmark.notes import STYLES, Note, Planted, generate

RESULTS_PATH = Path(__file__).parent / "RESULTS.md"


class PlainPresidio:
    """Presidio's default analyser with nothing added, for comparison."""

    def __init__(self) -> None:
        force_offline()
        self.analyzer = AnalyzerEngine()

    def scrub(self, text: str, token_map: TokenMap) -> ScrubResult:
        from collections import Counter

        from app.core.sanitizer import merge_overlaps

        out, cursor = [], 0
        for r in merge_overlaps(self.analyzer.analyze(text=text, language="en", score_threshold=0.4)):
            out += [text[cursor : r.start], token_map.token_for(r.entity_type, text[r.start : r.end])]
            cursor = r.end
        return ScrubResult("".join(out) + text[cursor:], Counter())


def survives(part: str, text: str) -> bool:
    return re.search(rf"(?<![\w]){re.escape(part)}(?![\w])", text) is not None


def leaked(p: Planted, scrubbed: str) -> list[str]:
    return [part for part in p.parts if survives(part, scrubbed)]


def run(notes: list[Note], sanitiser: Sanitiser) -> dict:
    by_kind: dict[str, list[int]] = defaultdict(lambda: [0, 0])  # caught, total
    by_style: dict[str, list[int]] = defaultdict(lambda: [0, 0])  # clean notes, total
    hard = [0, 0]
    keep = [0, 0]
    leaks: list[tuple[str, str, str, list[str]]] = []
    started = time.perf_counter()

    for note in notes:
        scrubbed = sanitiser.scrub(note.text, TokenMap()).text
        clean = True
        for p in note.planted:
            missed = leaked(p, scrubbed)
            bucket = hard if p.hard else by_kind[p.kind]
            bucket[1] += 1
            if missed:
                clean = False
                leaks.append((note.style, p.kind, p.value, missed))
            else:
                bucket[0] += 1
        by_style[note.style][1] += 1
        by_style[note.style][0] += clean
        for phrase in note.keep:
            keep[1] += 1
            keep[0] += phrase in scrubbed

    elapsed = time.perf_counter() - started
    standard = [sum(v[0] for v in by_kind.values()), sum(v[1] for v in by_kind.values())]
    return {
        "notes": len(notes),
        "by_kind": dict(by_kind),
        "by_style": dict(by_style),
        "standard": standard,
        "hard": hard,
        "keep": keep,
        "leaks": leaks,
        "ms_per_note": elapsed * 1000 / len(notes),
    }


def pct(pair: list[int]) -> str:
    return f"{100 * pair[0] / pair[1]:.1f}%" if pair[1] else "n/a"


KIND_LABELS = {"PERSON_UNSEEN": "PERSON (names on none of Haven's lists)"}


def report(r: dict, baseline: dict | None = None) -> str:
    lines = [
        "# Haven benchmark results",
        "",
        f"{r['notes']} fictional clinical notes in {len(STYLES)} styles, generated by `benchmark/notes.py` "
        "(seed 2026). Re-run with `python -m benchmark.run`.",
        "",
        "These notes were written by the same people who wrote Haven's recognisers, so treat the numbers "
        "as an upper bound. Real notes are messier.",
        "",
        "## Summary",
        "",
        "| Measure | Result |",
        "|---|---|",
        f"| Identifiers caught (standard cases) | {pct(r['standard'])} "
        f"({r['standard'][0]}/{r['standard'][1]}) |",
        f"| Identifiers caught (hard cases) | {pct(r['hard'])} ({r['hard'][0]}/{r['hard'][1]}) |",
        f"| Clinical phrases left intact | {pct(r['keep'])} ({r['keep'][0]}/{r['keep'][1]}) |",
        f"| Average time per note | {r['ms_per_note']:.0f} ms |",
        "",
        *(
            [
                f"For comparison, Presidio on its own (default settings, same notes) caught "
                f"{pct(baseline['standard'])} of standard identifiers and left {pct(baseline['keep'])} of "
                "clinical phrases intact. The difference is Haven's own recognisers.",
                "",
            ]
            if baseline
            else []
        ),
        "Hard cases are names that are also ordinary words (Grace Hill, Will Bell) and names typed in "
        "lower case.",
        "",
        "## By identifier type",
        "",
        "| Type | Haven | Presidio alone |" if baseline else "| Type | Caught |",
        "|---|---|---|" if baseline else "|---|---|",
    ]
    for kind, pair in sorted(r["by_kind"].items()):
        row = f"| {KIND_LABELS.get(kind, kind)} | {pct(pair)} ({pair[0]}/{pair[1]}) |"
        if baseline:
            row += f" {pct(baseline['by_kind'].get(kind, [0, 0]))} |"
        lines.append(row)
    lines += ["", "## Notes with no leaks at all, by style", "", "| Style | Clean notes |", "|---|---|"]
    for style in STYLES:
        pair = r["by_style"][style]
        lines.append(f"| {style.replace('_', ' ')} | {pct(pair)} ({pair[0]}/{pair[1]}) |")
    if r["leaks"]:
        lines += [
            "",
            "## Examples of what got through",
            "",
            "| Style | Type | Planted | Left in text |",
            "|---|---|---|---|",
        ]
        seen: set[tuple[str, str]] = set()
        for style, kind, value, missed in r["leaks"]:
            if (style, kind) in seen:
                continue
            seen.add((style, kind))
            lines.append(f"| {style.replace('_', ' ')} | {kind} | {value} | {', '.join(missed)} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--per-style", type=int, default=25)
    parser.add_argument("--show", type=int, default=0, help="Print this many leaks")
    parser.add_argument("--no-write", action="store_true")
    args = parser.parse_args()

    notes = generate(args.per_style)
    r = run(notes, Sanitiser())
    baseline = run(notes, PlainPresidio())  # type: ignore[arg-type]
    print(
        f"Standard identifiers caught: {pct(r['standard'])}  Hard cases: {pct(r['hard'])}  "
        f"Clinical phrases kept: {pct(r['keep'])}  {r['ms_per_note']:.0f} ms/note"
    )
    print(f"Presidio alone: {pct(baseline['standard'])} standard, {pct(baseline['keep'])} phrases kept")
    for kind, pair in sorted(r["by_kind"].items()):
        b = pct(baseline["by_kind"].get(kind, [0, 0]))
        print(f"  {kind:<14} {pct(pair):>7}  ({pair[0]}/{pair[1]})   Presidio alone {b}")
    for style, kind, value, missed in r["leaks"][: args.show]:
        print(f"  LEAK {style:<20} {kind:<9} {value!r} -> {missed}")
    if not args.no_write:
        RESULTS_PATH.write_text(report(r, baseline), encoding="utf-8")
        print(f"Wrote {RESULTS_PATH}")


if __name__ == "__main__":
    main()
